/**
 * Safe rendering of external email HTML (plan §8, Revision 3). Layers:
 * 1. sanitize-html with a tag and attribute allowlist: removes scripts, frames, forms, event
 *    handlers and dangerous URLs. `<img src/srcset>` is the only image path (data: always,
 *    absolute https: only with "Show remote images").
 * 2. All CSS (style elements and style attributes) is parsed and regenerated from an allowlist
 *    by `email-css.ts`. CSS never loads anything, in either mode.
 * 3. A structural check on the final string; on failure no HTML is returned.
 * 4. The stored result is shown in an iframe with `sandbox` (no allow-scripts, no allow-same-origin)
 *    and a restrictive meta CSP, built by `emailShell` (src/lib/email/shell.ts).
 *
 * Revision 4: this runs only at ingest, inside the time-limited render worker
 * (src/lib/email/render.worker.ts), never on a page view.
 */

export type RenderOptions = { allowRemoteImages: boolean };

export { MAX_CSS_CHARS };

/** Largest HTML body sanitized as HTML (256 Ki UTF-16 code units, owner Round 8 "C"); larger bodies are rendered as plain text at ingest. */
export const MAX_HTML_CHARS = 262_144;


const COMMON_ATTRS = [
  "style", "class", "id", "dir", "lang", "title", "align", "valign", "width", "height", "bgcolor", "color",
  "border", "cellpadding", "cellspacing", "colspan", "rowspan", "nowrap", "span",
];

/**
 * The sanitize-html attribute allowlist. postcheck.ts keeps an import-free copy
 * (EMAIL_ALLOWED_ATTRIBUTES) for the main-thread render check; a test asserts they are equal.
 */
export const SANITIZER_ALLOWED_ATTRIBUTES: Record<string, string[]> = {
  "*": COMMON_ATTRS,
  a: ["href", "name", "target", "rel"],
  img: ["src", "srcset", "alt", "width", "height"],
  font: ["face", "size", "color"],
  table: ["summary"],
  ol: ["start", "type"],
  ul: ["type"],
  li: ["value"],
};

/** True for an absolute https: URL. */
function isHttpsUrl(url: string): boolean {
  return /^\s*https:\/\//i.test(url);
}

/**
 * Allowed `<img src>` values: `data:` URLs, plus absolute `https:` URLs when remote images are
 * allowed. Everything else (relative, protocol-relative, http, other schemes) is removed.
 */
export function isAllowedImageUrl(url: string, opts: RenderOptions): boolean {
  if (/^\s*data:/i.test(url)) return true;
  return opts.allowRemoteImages && isHttpsUrl(url);
}

/** srcset with only allowed candidates (https when remote images are allowed), or null to drop it. */
function filterSrcset(srcset: string, opts: RenderOptions): string | null {
  if (!opts.allowRemoteImages) return null;
  // Plain split plus trim: a /\s*,\s*/ split backtracks quadratically on long whitespace runs.
  const kept = srcset
    .split(",")
    .map((c) => c.trim())
    .filter((c) => c.length > 0 && isHttpsUrl(c.split(/\s+/)[0]!));
  return kept.length > 0 ? kept.join(", ") : null;
}

/** ASCII-only lowercasing: unlike toLowerCase(), it never changes the string's length, so indexes stay aligned. */
const asciiLower = (s: string) => s.replace(/[A-Z]/g, (c) => String.fromCharCode(c.charCodeAt(0) + 32));

/**
 * Deprecated name kept only so existing callers compile: it is `sanitizeStylesheet`, the
 * Revision 3 parser-based implementation (the old regex/scanner filter is deleted). CSS output
 * no longer depends on the render mode, so `_opts` is ignored.
 */
export function sanitizeCss(css: string, _opts?: RenderOptions): string {
  return sanitizeStylesheet(css);
}

function sanitizerOptions(opts: RenderOptions, budget: CssBudget): sanitizeHtml.IOptions {
  const imgSchemes = opts.allowRemoteImages ? ["https", "data"] : ["data"];
  return {
    allowedTags: ALLOWED_TAGS,
    // <style> is allowed because most HTML email depends on it; its text is regenerated by sanitizeStylesheet.
    allowVulnerableTags: true,
    allowedAttributes: SANITIZER_ALLOWED_ATTRIBUTES,
    allowedSchemes: ["http", "https", "mailto", "tel"],
    allowedSchemesByTag: { img: imgSchemes },
    allowedSchemesAppliedToAttributes: ["href", "src", "cite"],
    allowProtocolRelative: false,
    disallowedTagsMode: "discard",
    // sanitize-html would otherwise re-parse and re-serialize every style attribute with postcss
    // (index.js, `if (a === 'style') { if (options.parseStyleAttributes) …`), even without
    // allowedStyles. sanitizeStyleAttribute owns style attributes, so that is switched off.
    parseStyleAttributes: false,
    // Contents of these are dropped together with the tag (title/head text would otherwise show as body text).
    nonTextTags: ["script", "style", "textarea", "option", "xmp", "title", "noscript", "template", "noembed", "noframes"],
    transformTags: {
      "*": (tagName, attribs) => {
        const next = { ...attribs };
        if (next.style !== undefined) {
          // The value is already entity-decoded by htmlparser2, as the browser sees it.
          const css = sanitizeStyleAttribute(next.style, budget);
          if (css) next.style = css;
          else delete next.style;
        }
        return { tagName, attribs: next };
      },
      a: (tagName, attribs) => ({
        tagName,
        attribs: { ...attribs, target: "_blank", rel: "noopener noreferrer" },
      }),
      img: (tagName, attribs) => {
        const src = attribs.src ?? "";
        if (/^\s*cid:/i.test(src)) {
          // Inline (cid:) images aren't fetched in 2a: show a placeholder instead.
          return { tagName: "span", attribs: { class: "alex-inline-image" }, text: `[inline image${attribs.alt ? `: ${attribs.alt}` : ""}]` };
        }
        const next = { ...attribs };
        if (next.src !== undefined && !isAllowedImageUrl(next.src, opts)) delete next.src;
        if (next.srcset !== undefined) {
          const srcset = filterSrcset(next.srcset, opts);
          if (srcset) next.srcset = srcset;
          else delete next.srcset;
        }
        return { tagName, attribs: next };
      },
    },
  };
}


export type SanitizeResult = { ok: true; html: string } | { ok: false; reason: "too_large" | "postcheck" };

/**
 * Sanitizes email HTML (plan Revision 4: called only at ingest, inside the render worker).
 * `allowRemoteImages` affects `<img src/srcset>` only. Over MAX_HTML_CHARS, or if the structural
 * check fails, it returns a failure reason and the caller stores a plain-text rendering instead
 * (src/lib/email/render.ts); no text fallback is produced here.
 */
export function sanitizeEmailHtmlResult(html: string, opts: RenderOptions = { allowRemoteImages: false }): SanitizeResult {
  if (html.length > MAX_HTML_CHARS) return { ok: false, reason: "too_large" };
  const budget = new CssBudget(); // MAX_CSS_PER_MESSAGE across all of this message's CSS
  const clean = sanitizeHtml(html, sanitizerOptions(opts, budget));
  // <style> text passes through sanitize-html raw; replace each element's text with the
  // regenerated stylesheet. sanitize-html always emits `</style>`, so a plain indexOf walk finds
  // each element (linear).
  const lower = asciiLower(clean);
  const out: string[] = []; // joined once below (no growing-string accumulator)
  let pos = 0;
  for (;;) {
    const open = lower.indexOf("<style", pos);
    if (open < 0) break;
    const openEnd = clean.indexOf(">", open);
    const close = openEnd < 0 ? -1 : lower.indexOf("</style>", openEnd);
    if (close < 0) break; // left as is; the structural check below rejects it
    out.push(clean.slice(pos, openEnd + 1), sanitizeStylesheet(clean.slice(openEnd + 1, close), budget));
    pos = close;
  }
  out.push(clean.slice(pos));
  const result = out.join("");
  // Guarantee on the final string: if the check fails, nothing is returned as HTML.
  return isStructurallySafe(result) ? { ok: true, html: result } : { ok: false, reason: "postcheck" };
}

/**
 * String-returning wrapper kept for existing tests and tools: the sanitized HTML, or "" when
 * sanitizeEmailHtmlResult refuses the input (too large, or failed the structural check). The
 * application path uses renderEmailBody (src/lib/email/render.ts), which turns those failures into
 * a stored plain-text rendering.
 */
export function sanitizeEmailHtml(html: string, opts: RenderOptions = { allowRemoteImages: false }): string {
  const r = sanitizeEmailHtmlResult(html, opts);
  return r.ok ? r.html : "";
}

/** Test helper only (nothing under src/app imports it): sanitize, then wrap in the srcdoc shell. */
export function emailDocument(html: string, opts: RenderOptions = { allowRemoteImages: false }): string {
  return emailShell(sanitizeEmailHtml(html, opts), opts);
}

